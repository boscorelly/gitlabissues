#!/usr/bin/env python3
"""Generates public/css/gitlabissues.css from logo.png (single source of truth for the plugin's icon).

GLPI 11 only serves a plugin's static files from its `public/` directory, while GLPI itself reads the
plugin icon from `logo.png` at the root. Rather than keeping two copies of the image, the stylesheet that
draws the icon of the plugin's tabs embeds logo.png as a data URI. Run again after changing logo.png.
"""
import base64, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
png = open(os.path.join(ROOT, 'logo.png'), 'rb').read()
css = f'''/* Generated by tools/logo-css.py from logo.png: do not edit by hand.
 * The plugin's logo, used as the icon of its tabs. */
.gitlabissues-icon {{
    display: inline-block;
    width: 1.25em;
    height: 1.25em;
    vertical-align: -0.25em;
    background: url("data:image/png;base64,{base64.b64encode(png).decode()}") center / contain no-repeat;
}}
'''
os.makedirs(os.path.join(ROOT, 'public', 'css'), exist_ok=True)
open(os.path.join(ROOT, 'public', 'css', 'gitlabissues.css'), 'w').write(css)
print(f'public/css/gitlabissues.css written ({len(css)} bytes, logo {len(png)} bytes)')
